export type { IconWeight }

export const defaultIconWeight: IconWeight = 'regular'

/** Phosphor props plus lucide's stroke props, which are accepted and ignored. */
export type IconProps = Omit<PhosphorIconProps, 'ref'> & { strokeWidth?: number | string; absoluteStrokeWidth?: boolean }
export type LucideProps = IconProps
export type LucideIcon = ForwardRefExoticComponent<IconProps & RefAttributes<SVGSVGElement>>

function adapt(Base: PhosphorIcon, name: string, defaults?: Partial<PhosphorIconProps>): LucideIcon {
  const Adapted = forwardRef<SVGSVGElement, IconProps>((props, ref) => {
    const { strokeWidth, absoluteStrokeWidth, size = 24, weight = defaultIconWeight, ...rest } = props
    void strokeWidth
    void absoluteStrokeWidth
    return <Base ref={ref} {...defaults} size={size} weight={weight} {...rest} />
  })
  Adapted.displayName = name
  return Adapted
}

